import 'dart:convert';
import 'dart:io';
import 'package:flutter/foundation.dart';
import 'package:path_provider/path_provider.dart';
import 'package:share_plus/share_plus.dart';
import '../../data/models/transaction_model.dart';
import '../../providers/currency_provider.dart';
import 'formatters.dart';

class ExportService {
  /// Generates RFC-4180 compliant CSV statement with formula injection protection
  static String generateCsvStatement(
    List<TransactionModel> transactions,
    CurrencyInfo currency,
  ) {
    final buffer = StringBuffer();

    // CSV Header
    buffer.writeln(
      'Transaction ID,Date,Type,Symbol,Asset Name,Units,Price (USD),Gross Total (USD),Fee (USD),Original Currency,Original Amount,FX Rate to USD,Notes',
    );

    for (final tx in transactions) {
      final sanitizedNotes = _sanitizeCsvField(tx.notes);
      final sanitizedName = _sanitizeCsvField(tx.name ?? tx.symbol ?? '');
      final sanitizedSymbol = _sanitizeCsvField(tx.symbol ?? '');

      buffer.writeln(
        '${tx.id},'
        '${Formatters.date(tx.transactionDate)},'
        '${tx.type},'
        '$sanitizedSymbol,'
        '$sanitizedName,'
        '${tx.amount},'
        '${tx.pricePerUnit},'
        '${tx.totalAmount},'
        '${tx.fee},'
        '${tx.originalCurrency},'
        '${tx.originalAmount ?? tx.amount},'
        '${tx.fxToBase},'
        '$sanitizedNotes',
      );
    }

    return buffer.toString();
  }

  /// Exports and shares CSV file via native OS share sheet
  static Future<bool> shareCsvStatement(
    List<TransactionModel> transactions,
    CurrencyInfo currency,
  ) async {
    try {
      final csv = generateCsvStatement(transactions, currency);
      final dir = await getTemporaryDirectory();
      final dateStr = DateTime.now().toIso8601String().substring(0, 10);
      final file = File('${dir.path}/asset_manager_statement_$dateStr.csv');
      await file.writeAsString(csv);

      final xFile = XFile(file.path, mimeType: 'text/csv');
      final result = await SharePlus.instance.share(
        ShareParams(
          files: [xFile],
          subject: 'Asset Manager Financial Statement ($dateStr)',
          text: 'Financial ledger export generated by Asset Manager.',
        ),
      );

      return result.status == ShareResultStatus.success ||
          result.status == ShareResultStatus.dismissed;
    } catch (e) {
      debugPrint('[ExportService] Share CSV error: $e');
      return false;
    }
  }

  /// Generates versioned JSON backup format
  static String generateJsonBackup({
    required List<TransactionModel> transactions,
    required String currencyCode,
  }) {
    final Map<String, dynamic> backup = {
      'version': '1.0.0',
      'schema_version': 2,
      'exported_at': DateTime.now().toIso8601String(),
      'currency': currencyCode,
      'transactions_count': transactions.length,
      'transactions': transactions.map((t) => t.toJson()).toList(),
    };

    return jsonEncode(backup);
  }

  /// Prevents CSV formula injection and properly escapes commas/quotes
  static String _sanitizeCsvField(String text) {
    var val = text.trim();
    if (val.isEmpty) return '""';

    // Prevent spreadsheet formula injection (=, +, -, @, tab, cr)
    if (val.startsWith('=') ||
        val.startsWith('+') ||
        val.startsWith('-') ||
        val.startsWith('@') ||
        val.startsWith('\t') ||
        val.startsWith('\r')) {
      val = "'$val";
    }

    // Escape quotes
    val = val.replaceAll('"', '""');
    return '"$val"';
  }
}
