/// Monthly summary representation for analytics and comparative reporting
class MonthlyCashflowReport {
  final String yearMonth; // e.g. "2026-10"
  final double totalIncome;
  final double totalExpense;
  final double totalInvested;
  final Map<String, double> incomeByCategory;
  final Map<String, double> expenseByCategory;
  final Map<String, double> investmentByCategory;

  const MonthlyCashflowReport({
    required this.yearMonth,
    required this.totalIncome,
    required this.totalExpense,
    required this.totalInvested,
    required this.incomeByCategory,
    required this.expenseByCategory,
    required this.investmentByCategory,
  });

  double get netCashflow => totalIncome - totalExpense - totalInvested;
  double get savingsRate => totalIncome > 0 ? ((totalIncome - totalExpense) / totalIncome) * 100 : 0.0;

  String get displayName {
    try {
      final parts = yearMonth.split('-');
      if (parts.length == 2) {
        final d = DateTime(int.parse(parts[0]), int.parse(parts[1]), 1);
        return DateFormat('MMM yyyy').format(d);
      }
    } catch (_) {}
    return yearMonth;
  }
}

