import 'package:intl/intl.dart';

enum CashRecordType {
  income('INCOME', 'Income'),
  expense('EXPENSE', 'Expense'),
  investmentTransfer('INVESTMENT_TRANSFER', 'Investment');

  final String value;
  final String label;
  const CashRecordType(this.value, this.label);

  static CashRecordType fromString(String val) {
    return CashRecordType.values.firstWhere(
      (e) => e.value.toUpperCase() == val.toUpperCase(),
      orElse: () => CashRecordType.expense,
    );
  }
}

class BankAccountModel {
  final String id;
  final String userId;
  final String bankName;
  final String accountNumber;
  final double initialBalance;
  final DateTime initialBalanceDate;
  final String currency;
  final bool autoCreditSalary;
  final String salaryStartMonth; // e.g. '2026-11'
  final String notes;

  const BankAccountModel({
    required this.id,
    required this.userId,
    this.bankName = 'Commercial Bank',
    this.accountNumber = '',
    this.initialBalance = 0.0,
    required this.initialBalanceDate,
    this.currency = 'LKR',
    this.autoCreditSalary = true,
    this.salaryStartMonth = '',
    this.notes = '',
  });

  factory BankAccountModel.empty() {
    final now = DateTime.now();
    final nextMonthStr = DateFormat('yyyy-MM').format(DateTime(now.year, now.month + 1, 1));
    return BankAccountModel(
      id: '',
      userId: '',
      bankName: 'Commercial Bank',
      accountNumber: '',
      initialBalance: 0.0,
      initialBalanceDate: now,
      currency: 'LKR',
      autoCreditSalary: true,
      salaryStartMonth: nextMonthStr,
      notes: '',
    );
  }

  Map<String, dynamic> toJson() => {
        'id': id.isEmpty ? null : id,
        'user_id': userId,
        'bank_name': bankName,
        'account_number': accountNumber,
        'initial_balance': initialBalance,
        'initial_balance_date': initialBalanceDate.toIso8601String().split('T').first,
        'currency': currency,
        'auto_credit_salary': autoCreditSalary,
        'salary_start_month': salaryStartMonth,
        'notes': notes,
      };

  factory BankAccountModel.fromJson(Map<String, dynamic> json) => BankAccountModel(
        id: json['id'] as String? ?? '',
        userId: json['user_id'] as String? ?? '',
        bankName: json['bank_name'] as String? ?? 'Commercial Bank',
        accountNumber: json['account_number'] as String? ?? '',
        initialBalance: (json['initial_balance'] as num?)?.toDouble() ?? 0.0,
        initialBalanceDate: DateTime.tryParse(json['initial_balance_date'] as String? ?? '') ?? DateTime.now(),
        currency: json['currency'] as String? ?? 'LKR',
        autoCreditSalary: json['auto_credit_salary'] as bool? ?? true,
        salaryStartMonth: json['salary_start_month'] as String? ?? '',
        notes: json['notes'] as String? ?? '',
      );

  BankAccountModel copyWith({
    String? id,
    String? userId,
    String? bankName,
    String? accountNumber,
    double? initialBalance,
    DateTime? initialBalanceDate,
    String? currency,
    bool? autoCreditSalary,
    String? salaryStartMonth,
    String? notes,
  }) {
    return BankAccountModel(
      id: id ?? this.id,
      userId: userId ?? this.userId,
      bankName: bankName ?? this.bankName,
      accountNumber: accountNumber ?? this.accountNumber,
      initialBalance: initialBalance ?? this.initialBalance,
      initialBalanceDate: initialBalanceDate ?? this.initialBalanceDate,
      currency: currency ?? this.currency,
      autoCreditSalary: autoCreditSalary ?? this.autoCreditSalary,
      salaryStartMonth: salaryStartMonth ?? this.salaryStartMonth,
      notes: notes ?? this.notes,
    );
  }
}

class CashRecordModel {
  final String id;
  final String userId;
  final String type; // 'INCOME', 'EXPENSE', 'INVESTMENT_TRANSFER'
  final String category;
  final double amount;
  final DateTime recordDate;
  final String yearMonth; // 'YYYY-MM'
  final String notes;
  final String? sourceEmploymentId;
  final bool isAutoGenerated;

  const CashRecordModel({
    required this.id,
    required this.userId,
    required this.type,
    required this.category,
    required this.amount,
    required this.recordDate,
    required this.yearMonth,
    this.notes = '',
    this.sourceEmploymentId,
    this.isAutoGenerated = false,
  });

  bool get isIncome => type == 'INCOME';
  bool get isExpense => type == 'EXPENSE';
  bool get isInvestment => type == 'INVESTMENT_TRANSFER';

  Map<String, dynamic> toJson() => {
        'id': id.isEmpty ? null : id,
        'user_id': userId,
        'type': type,
        'category': category,
        'amount': amount,
        'record_date': recordDate.toIso8601String().split('T').first,
        'year_month': yearMonth,
        'notes': notes,
        'source_employment_id': sourceEmploymentId,
        'is_auto_generated': isAutoGenerated,
      };

  factory CashRecordModel.fromJson(Map<String, dynamic> json) {
    final parsedDate = DateTime.tryParse(json['record_date'] as String? ?? '') ?? DateTime.now();
    final ym = json['year_month'] as String? ?? DateFormat('yyyy-MM').format(parsedDate);
    return CashRecordModel(
      id: json['id'] as String? ?? '',
      userId: json['user_id'] as String? ?? '',
      type: json['type'] as String? ?? 'EXPENSE',
      category: json['category'] as String? ?? 'General',
      amount: (json['amount'] as num?)?.toDouble() ?? 0.0,
      recordDate: parsedDate,
      yearMonth: ym,
      notes: json['notes'] as String? ?? '',
      sourceEmploymentId: json['source_employment_id'] as String?,
      isAutoGenerated: json['is_auto_generated'] as bool? ?? false,
    );
  }
}

