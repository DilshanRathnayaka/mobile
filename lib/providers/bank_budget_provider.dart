final bankBudgetProvider =
    StateNotifierProvider<BankBudgetNotifier, AsyncValue<BankBudgetSummary>>((ref) {
  final supabase = ref.watch(supabaseServiceProvider);
  return BankBudgetNotifier(supabase, ref);
});

class BankBudgetNotifier extends StateNotifier<AsyncValue<BankBudgetSummary>> {
  static const _prefAccountKey = 'local_bank_account_data';
  static const _prefRecordsKey = 'local_cash_records_data';
  static const _prefPlanKey = 'local_budget_plan_data';
  static const _prefDismissedSalaryKey = 'dismissed_auto_salary_months';

  final SupabaseService _supabase;
  final Ref _ref;

  BankBudgetNotifier(this._supabase, this._ref) : super(const AsyncValue.loading()) {
    loadData();
  }

  Future<Set<String>> _getDismissedSalaryMonths() async {
    try {
      final prefs = await SharedPreferences.getInstance();
      final list = prefs.getStringList(_prefDismissedSalaryKey) ?? [];
      return list.toSet();
    } catch (_) {
      return {};
    }
  }

  Future<void> _dismissAutoSalaryMonth(String ym) async {
    try {
      final prefs = await SharedPreferences.getInstance();
      final set = (prefs.getStringList(_prefDismissedSalaryKey) ?? []).toSet();
      set.add(ym);
      await prefs.setStringList(_prefDismissedSalaryKey, set.toList());
    } catch (_) {}
  }

  Future<void> loadData() async {
    try {
      BankAccountModel account = BankAccountModel.empty();
      List<CashRecordModel> records = [];
      MonthlyBudgetPlanModel plan = MonthlyBudgetPlanModel.defaults();

      // 1. Try Supabase cloud first
      if (_supabase.isAuthenticated) {
        final cloudAccount = await _supabase.getBankAccount();
        if (cloudAccount != null) account = cloudAccount;

        final cloudRecords = await _supabase.getCashRecords();
        if (cloudRecords.isNotEmpty) records = cloudRecords;

        final cloudPlan = await _supabase.getBudgetPlan();
        if (cloudPlan != null) plan = cloudPlan;
      }

      // 2. Fallback to local storage if empty
      final prefs = await SharedPreferences.getInstance();
      if (account.id.isEmpty) {
        final rawAcc = prefs.getString(_prefAccountKey);
        if (rawAcc != null) {
          try {
            account = BankAccountModel.fromJson(jsonDecode(rawAcc));
          } catch (_) {}
        }
      }

      if (records.isEmpty) {
        final rawRecs = prefs.getStringList(_prefRecordsKey);
        if (rawRecs != null && rawRecs.isNotEmpty) {
          try {
            records = rawRecs.map((e) => CashRecordModel.fromJson(jsonDecode(e))).toList();
          } catch (_) {}
        }
      }

      if (plan.id.isEmpty) {
        final rawPlan = prefs.getString(_prefPlanKey);
        if (rawPlan != null) {
          try {
            plan = MonthlyBudgetPlanModel.fromJson(jsonDecode(rawPlan));
          } catch (_) {}
        }
      }

      // Purge any auto-generated salary records that belong to dismissed months or prior to salaryStartMonth
      final dismissedMonths = await _getDismissedSalaryMonths();
      final now = DateTime.now();
      final nextMonthStr = DateFormat('yyyy-MM').format(DateTime(now.year, now.month + 1, 1));
      final effectiveStartMonth = account.salaryStartMonth.isNotEmpty ? account.salaryStartMonth : nextMonthStr;

      final cleanedRecords = <CashRecordModel>[];
      for (final r in records) {
        if (r.isAutoGenerated && r.category == 'Salary') {
          final isDismissed = dismissedMonths.contains(r.yearMonth);
          final isBeforeStart = r.yearMonth.compareTo(effectiveStartMonth) < 0;
          if (isDismissed || isBeforeStart) {
            if (_supabase.isAuthenticated && r.id.isNotEmpty) {
              _supabase.deleteCashRecord(r.id).catchError((_) => false);
            }
            continue; // Skip - permanently removed!
          }
        }
        cleanedRecords.add(r);
      }
      records = cleanedRecords;

      // 3. Automated Monthly Salary Inflow Check
      records = await _checkAndApplySalaryInflows(account, records);

      // 4. Calculate full analytics and set state
      final summary = _calculateSummary(account, records, plan);
      state = AsyncValue.data(summary);

      // Persist cache locally
      _saveLocalCache(account, records, plan);
    } catch (e, st) {
      debugPrint('[BankBudgetNotifier] loadData error: $e');
      state = AsyncValue.error(e, st);
    }
  }

  /// Automatically projects or credits monthly salary from active employment
  Future<List<CashRecordModel>> _checkAndApplySalaryInflows(
    BankAccountModel account,
    List<CashRecordModel> currentRecords,
  ) async {
    if (!account.autoCreditSalary) return currentRecords;

    final employmentsAsync = _ref.read(employmentListProvider);
    final employments = employmentsAsync.asData?.value ?? [];
    if (employments.isEmpty) return currentRecords;

    final currentJob = employments.firstWhere(
      (j) => j.isCurrent && !j.isResigned,
      orElse: () => employments.first,
    );

    final netSalary = currentJob.monthlyNetSalary;
    if (netSalary <= 0) return currentRecords;

    final updatedList = List<CashRecordModel>.from(currentRecords);
    final now = DateTime.now();

    // Determine candidate year-months to check for auto-crediting:
    // Respect account.salaryStartMonth: if user configured starting from next month (e.g. 2026-11),
    // we strictly skip any month prior to that starting month!
    final nextMonth = DateTime(now.year, now.month + 1, 1);
    final candidateMonths = <DateTime>[];
    DateTime startMonth;
    if (account.salaryStartMonth.isNotEmpty) {
      try {
        final parts = account.salaryStartMonth.split('-');
        startMonth = DateTime(int.parse(parts[0]), int.parse(parts[1]), 1);
      } catch (_) {
        startMonth = nextMonth;
      }
    } else {
      // By default, salary auto-credit ALWAYS starts from NEXT MONTH!
      // Current month's salary is already included in the user's initial bank balance baseline!
      startMonth = nextMonth;
    }

    final currentMonth = DateTime(now.year, now.month, 1);

    // If startMonth is in the future (e.g. next month 2026-11 and current is 2026-10),
    // currentMonth is before startMonth so candidateMonths stays empty.
    if (!currentMonth.isBefore(startMonth)) {
      var iter = startMonth;
      while (!iter.isAfter(currentMonth)) {
        candidateMonths.add(iter);
        iter = DateTime(iter.year, iter.month + 1, 1);
      }
    }

    final dismissedMonths = await _getDismissedSalaryMonths();
    bool addedAny = false;

    for (final monthDate in candidateMonths) {
      final ymStr = DateFormat('yyyy-MM').format(monthDate);
      if (dismissedMonths.contains(ymStr)) {
        continue; // User explicitly deleted/dismissed this month's salary! Do not re-add!
      }
      final alreadyCredited = updatedList.any(
        (r) => r.yearMonth == ymStr && r.type == 'INCOME' && r.category == 'Salary',
      );

      // Credit if today is on or after salary day, or if it is the current month
      final salaryDay = currentJob.salaryDay.clamp(1, 28);
      final payDateThisMonth = DateTime(monthDate.year, monthDate.month, salaryDay);
      final isDueOrPast = now.isAfter(payDateThisMonth) || now.isAtSameMomentAs(payDateThisMonth);

      if (!alreadyCredited && isDueOrPast) {
        final newRecord = CashRecordModel(
          id: 'auto-sal-$ymStr',
          userId: account.userId,
          type: 'INCOME',
          category: 'Salary',
          amount: netSalary,
          recordDate: payDateThisMonth,
          yearMonth: ymStr,
          notes: 'Auto-credited monthly take-home salary from ${currentJob.companyName}',
          sourceEmploymentId: currentJob.id,
          isAutoGenerated: true,
        );

        if (_supabase.isAuthenticated) {
          try {
            final cloudItem = await _supabase.addCashRecord(newRecord);
            if (cloudItem != null) {
              updatedList.insert(0, cloudItem);
              addedAny = true;
              continue;
            }
          } catch (_) {}
        }
        updatedList.insert(0, newRecord);
        addedAny = true;
      }
    }

    if (addedAny) {
      updatedList.sort((a, b) => b.recordDate.compareTo(a.recordDate));
    }
    return updatedList;
  }

  /// Calculates complete analytics, running bank balance, and comparative monthly reports
  BankBudgetSummary _calculateSummary(
    BankAccountModel account,
    List<CashRecordModel> records,
    MonthlyBudgetPlanModel plan,
  ) {
    double totalIncome = 0;
    double totalExpense = 0;
    double totalInvested = 0;

    // Grouping for monthly reporting
    final Map<String, List<CashRecordModel>> byMonth = {};

    for (final r in records) {
      if (r.isIncome) {
        totalIncome += r.amount;
      } else if (r.isExpense) {
        totalExpense += r.amount;
      } else if (r.isInvestment) {
        totalInvested += r.amount;
      }

      byMonth.putIfAbsent(r.yearMonth, () => []).add(r);
    }

    final currentBalance = account.initialBalance + totalIncome - totalExpense - totalInvested;

    // Build monthly reports
    final List<MonthlyCashflowReport> monthlyReports = [];

    // Ensure current month is present even if no records yet
    final currentYm = DateFormat('yyyy-MM').format(DateTime.now());
    if (!byMonth.containsKey(currentYm)) {
      byMonth[currentYm] = [];
    }

    byMonth.forEach((ym, monthRecords) {
      double mIncome = 0;
      double mExpense = 0;
      double mInvest = 0;
      final Map<String, double> inCat = {};
      final Map<String, double> exCat = {};
      final Map<String, double> invCat = {};

      for (final r in monthRecords) {
        if (r.isIncome) {
          mIncome += r.amount;
          inCat[r.category] = (inCat[r.category] ?? 0.0) + r.amount;
        } else if (r.isExpense) {
          mExpense += r.amount;
          exCat[r.category] = (exCat[r.category] ?? 0.0) + r.amount;
        } else if (r.isInvestment) {
          mInvest += r.amount;
          invCat[r.category] = (invCat[r.category] ?? 0.0) + r.amount;
        }
      }

      monthlyReports.add(MonthlyCashflowReport(
        yearMonth: ym,
        totalIncome: mIncome,
        totalExpense: mExpense,
        totalInvested: mInvest,
        incomeByCategory: inCat,
        expenseByCategory: exCat,
        investmentByCategory: invCat,
      ));
    });

    // Sort months descending (latest month first)
    monthlyReports.sort((a, b) => b.yearMonth.compareTo(a.yearMonth));

    // Find peak income & expense months
    MonthlyCashflowReport? peakIncome;
    MonthlyCashflowReport? peakExpense;

    for (final report in monthlyReports) {
      if (report.totalIncome > 0) {
        if (peakIncome == null || report.totalIncome > peakIncome.totalIncome) {
          peakIncome = report;
        }
      }
      if (report.totalExpense > 0) {
        if (peakExpense == null || report.totalExpense > peakExpense.totalExpense) {
          peakExpense = report;
        }
      }
    }

    return BankBudgetSummary(
      account: account,
      records: records,
      plan: plan,
      currentBalance: currentBalance,
      totalIncomeAllTime: totalIncome,
      totalExpenseAllTime: totalExpense,
      totalInvestedAllTime: totalInvested,
      monthlyReports: monthlyReports,
      peakIncomeMonth: peakIncome,
      peakExpenseMonth: peakExpense,
    );
  }

