  Future<void> setInitialBankBalance({
    required double initialBalance,
    required String bankName,
    required String accountNumber,
    required String salaryStartMonth,
    required bool autoCreditSalary,
  }) async {
    final currentSummary = state.asData?.value ?? BankBudgetSummary.empty();
    final now = DateTime.now();
    final curYm = DateFormat('yyyy-MM').format(now);
    final nextMonthStr = DateFormat('yyyy-MM').format(DateTime(now.year, now.month + 1, 1));
    final effectiveStart = salaryStartMonth.isNotEmpty ? salaryStartMonth : nextMonthStr;

    // Permanently dismiss current month from auto salary crediting
    await _dismissAutoSalaryMonth(curYm);

    // Purge any auto-salary records for current month or prior so baseline is not double-counted
    final updatedRecords = <CashRecordModel>[];
    for (final r in currentSummary.records) {
      if (r.isAutoGenerated && r.category == 'Salary') {
        if (r.yearMonth.compareTo(effectiveStart) < 0 || r.yearMonth == curYm) {
          if (_supabase.isAuthenticated && r.id.isNotEmpty) {
            _supabase.deleteCashRecord(r.id).catchError((_) => false);
          }
          continue; // Purge!
        }
      }
      updatedRecords.add(r);
    }

    final updatedAccount = currentSummary.account.copyWith(
      initialBalance: initialBalance,
      bankName: bankName,
      accountNumber: accountNumber,
      salaryStartMonth: effectiveStart,
      autoCreditSalary: autoCreditSalary,
      initialBalanceDate: now,
    );

    if (_supabase.isAuthenticated) {
      try {
        final saved = await _supabase.upsertBankAccount(updatedAccount);
        if (saved != null) {
          _updateState(saved, updatedRecords, currentSummary.plan);
          return;
        }
      } catch (e) {
        debugPrint('[BankBudgetNotifier] setInitialBalance cloud sync error: $e');
      }
    }

    _updateState(updatedAccount, updatedRecords, currentSummary.plan);
  }

  Future<bool> addCashRecord({
    required String type,
    required String category,
    required double amount,
    required DateTime recordDate,
    String notes = '',
    String? sourceEmploymentId,
    bool isAutoGenerated = false,
  }) async {
    if (amount <= 0) return false;

    final currentSummary = state.asData?.value ?? BankBudgetSummary.empty();
    final ym = DateFormat('yyyy-MM').format(recordDate);

    final newRecord = CashRecordModel(
      id: 'cash-${DateTime.now().millisecondsSinceEpoch}',
      userId: currentSummary.account.userId,
      type: type,
      category: category,
      amount: amount,
      recordDate: recordDate,
      yearMonth: ym,
      notes: notes,
      sourceEmploymentId: sourceEmploymentId,
      isAutoGenerated: isAutoGenerated,
    );

    CashRecordModel savedRecord = newRecord;

    if (_supabase.isAuthenticated) {
      try {
        final cloudItem = await _supabase.addCashRecord(newRecord);
        if (cloudItem != null) {
          savedRecord = cloudItem;
        }
      } catch (e) {
        debugPrint('[BankBudgetNotifier] addCashRecord cloud sync notice: $e');
      }
    }

    final updatedList = [savedRecord, ...currentSummary.records];
    updatedList.sort((a, b) => b.recordDate.compareTo(a.recordDate));

    _updateState(currentSummary.account, updatedList, currentSummary.plan);
    return true;
  }

  Future<bool> deleteRecord(String recordId) async {
    final currentSummary = state.asData?.value;
    if (currentSummary == null) return false;

    // Check if target record is an auto salary, and permanently dismiss that month!
    for (final r in currentSummary.records) {
      if (r.id == recordId && r.category == 'Salary') {
        await _dismissAutoSalaryMonth(r.yearMonth);
        break;
      }
    }

    if (_supabase.isAuthenticated) {
      try {
        await _supabase.deleteCashRecord(recordId);
      } catch (e) {
        debugPrint('[BankBudgetNotifier] deleteRecord cloud sync error: $e');
      }
    }

    final updatedList = currentSummary.records.where((r) => r.id != recordId).toList();
    _updateState(currentSummary.account, updatedList, currentSummary.plan);
    return true;
  }

  Future<void> updateBudgetPlan(MonthlyBudgetPlanModel newPlan) async {
    final currentSummary = state.asData?.value ?? BankBudgetSummary.empty();

    if (_supabase.isAuthenticated) {
      try {
        final saved = await _supabase.upsertBudgetPlan(newPlan);
        if (saved != null) {
          _updateState(currentSummary.account, currentSummary.records, saved);
          return;
        }
      } catch (e) {
        debugPrint('[BankBudgetNotifier] updateBudgetPlan cloud error: $e');
      }
    }

    _updateState(currentSummary.account, currentSummary.records, newPlan);
  }

  /// Manually force-credits next month's or selected month's salary for immediate projection
  Future<bool> creditSalaryForMonth(String targetYearMonth) async {
    final employmentsAsync = _ref.read(employmentListProvider);
    final employments = employmentsAsync.asData?.value ?? [];
    if (employments.isEmpty) return false;

    final currentJob = employments.firstWhere(
      (j) => j.isCurrent && !j.isResigned,
      orElse: () => employments.first,
    );

    final netSalary = currentJob.monthlyNetSalary;
    if (netSalary <= 0) return false;

    // Check if already credited
    final currentSummary = state.asData?.value;
    if (currentSummary != null) {
      final exists = currentSummary.records.any(
        (r) => r.yearMonth == targetYearMonth && r.type == 'INCOME' && r.category == 'Salary',
      );
      if (exists) return false; // Already present
    }

    DateTime parsedDate;
    try {
      final parts = targetYearMonth.split('-');
      parsedDate = DateTime(int.parse(parts[0]), int.parse(parts[1]), currentJob.salaryDay.clamp(1, 28));
    } catch (_) {
      parsedDate = DateTime.now();
    }

    return await addCashRecord(
      type: 'INCOME',
      category: 'Salary',
      amount: netSalary,
      recordDate: parsedDate,
      notes: 'Monthly salary credited from ${currentJob.companyName}',
      sourceEmploymentId: currentJob.id,
      isAutoGenerated: true,
    );
  }

  void _updateState(
    BankAccountModel account,
    List<CashRecordModel> records,
    MonthlyBudgetPlanModel plan,
  ) {
    final summary = _calculateSummary(account, records, plan);
    state = AsyncValue.data(summary);
    _saveLocalCache(account, records, plan);
  }

  Future<void> _saveLocalCache(
    BankAccountModel account,
    List<CashRecordModel> records,
    MonthlyBudgetPlanModel plan,
  ) async {
    try {
      final prefs = await SharedPreferences.getInstance();
      await prefs.setString(_prefAccountKey, jsonEncode(account.toJson()));
      await prefs.setStringList(
        _prefRecordsKey,
        records.map((r) => jsonEncode(r.toJson())).toList(),
      );
      await prefs.setString(_prefPlanKey, jsonEncode(plan.toJson()));
    } catch (_) {}
  }

  Future<void> refresh() async {
    await loadData();
  }
}
